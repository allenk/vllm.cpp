// fixture is the external reference that seals the DEQUANT arm bit for bit.
//
// Provenance of the INPUTS. Four SYNTHETIC 256-element blocks (4 x 56 = 224
// bytes), every byte drawn from std::mt19937 seeded 20260913 except the four
// nibbles that assemble the packed f16 super-block scale ((sc[0]>>12) |
// ((sc[1]>>8)&0xf0) | ((sc[2]>>4)&0xf00) | (sc[3]&0xf000) over the u16* view
// of scales: scales[1] hi, scales[3] lo, scales[5] hi, scales[7] hi), which
// are pinned so it decodes to a modest finite value (0x2C00 + 13*i: 0.03125
// .. 0.03620). The GSQ-RCO artifact this row unlocks was still
// downloading when this fixture was written, so real checkpoint bytes are
// owed; the synthetic bytes still exercise every field the decode reads (both
// delta polarities, all eight 3-bit sub-block scales, arbitrary grid indices).
//
